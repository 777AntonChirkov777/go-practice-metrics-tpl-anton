// Package agent реализует агент сбора метрик, который периодически
// собирает показатели работы процесса и хоста и отправляет их на сервер.
//
// Основной тип пакета — [Agent]. Его создаёт [NewAgent], а запускает [Agent.Start].
// Start сразу выполняет первый сбор через [Agent.CollectMetrics] и запускает горутины:
//   - сбор runtime-метрик (gauge из пакета runtime, а также PollCount и RandomValue)
//     с периодом pollInterval;
//   - сбор системных метрик (общая и свободная память, загрузка каждого процессора) с тем же периодом;
//   - диспетчер, который с периодом reportInterval делает снимок метрик и кладёт его
//     в очередь заданий;
//   - rateLimit воркеров, которые берут задания из очереди и отправляют их на сервер.
//
// Воркеры отправляют снимок одним запросом POST на адрес serverURL + "/updates/"
// с телом в виде JSON-массива метрик, сжатым gzip, и заголовками Content-Type
// (application/json) и Content-Encoding (gzip). Если задан ключ, в заголовке
// HashSHA256 передаётся подпись несжатого тела. Число одновременных отправок
// ограничено значением rateLimit. Отправка повторяется при временных ошибках
// (сетевые сбои, ответы 5xx, 408 и 429) через функцию Do пакета retry
// с интервалами retry.DefaultDelays; превышение таймаута запроса и отмена
// контекста повтор не вызывают.
//
// Все горутины агента работают, пока не отменён контекст, переданный в Start.
// После отмены контекста [Agent.Wait] блокируется до их завершения. Так агент
// используется в cmd/agent: значения интервалов, адрес сервера, ключ и rateLimit
// берутся из конфигурации агента.
