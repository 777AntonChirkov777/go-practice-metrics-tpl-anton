// Package audit реализует аудит запросов на обновление метрик: события
// об изменении метрик доставляются подписчикам-приёмникам, не задерживая
// обработку запроса.
//
// [Event] описывает одно событие: время в Unix-секундах, имена обновлённых
// метрик и IP-адрес клиента. Приёмник события реализует интерфейс [Observer].
// В пакете два приёмника: [FileSink] дописывает события в файл в формате
// JSON Lines, [HTTPSink] отправляет каждое событие запросом POST с JSON-телом
// на заданный URL.
//
// [Notifier] связывает хендлеры сервера с приёмниками. Приёмники добавляются
// через [Notifier.Subscribe], доставка запускается [Notifier.Start], а хендлеры
// вызывают [Notifier.Record], который кладёт событие в буферизованную очередь
// и при её переполнении отбрасывает событие, не блокируя вызывающий код.
// Одна фоновая горутина по очереди передаёт события всем приёмникам; ошибка
// доставки только записывается в журнал. [Notifier.Close] останавливает доставку,
// дожидается опустошения очереди в пределах тайм-аута и закрывает приёмники,
// реализующие io.Closer.
//
// В cmd/server приёмники создаются по флагам -audit-file и -audit-url
// (переменные окружения AUDIT_FILE и AUDIT_URL); если не задан ни один,
// аудит выключен и [Notifier.Enabled] возвращает false.
