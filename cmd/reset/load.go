const (
	genFile   = "reset.gen.go"
	genHeader = "// Code generated by cmd/reset; DO NOT EDIT."
)

type genError struct {
	file string
	line int
	col  int
	msg  string
}

type module struct {
	path string
	pkgs []*pkgInfo
}

type pkgInfo struct {
	path    string
	name    string
	dir     string
	genOurs bool
	foreign bool
	types   []*markedType
}

type markedType struct {
	name      string
	file      string
	offset    int
	tparams   int
	recv      string
	hasMethod bool
	invalid   bool
}

func (e genError) Error() string {
	return e.relative("")
}

func (e genError) relative(base string) string {
	msg := oneLine(e.msg)
	if e.file == "" {
		return msg
	}
	file := e.file
	if base != "" {
		if rel, err := filepath.Rel(base, file); err == nil && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
			file = rel
		}
	}
	switch {
	case e.line > 0 && e.col > 0:
		return fmt.Sprintf("%s:%d:%d: %s", file, e.line, e.col, msg)
	case e.line > 0:
		return fmt.Sprintf("%s:%d: %s", file, e.line, msg)
	}
	return file + ": " + msg
}

func oneLine(msg string) string {
	var parts []string
	for line := range strings.SplitSeq(msg, "\n") {
		if line = strings.TrimSpace(line); line != "" {
			parts = append(parts, line)
		}
	}
	return strings.Join(parts, "; ")
}

func posError(fset *token.FileSet, pos token.Pos, format string, args ...any) genError {
	p := fset.Position(pos)
	return genError{file: p.Filename, line: p.Line, col: p.Column, msg: fmt.Sprintf(format, args...)}
}

func compareErrors(a, b genError) int {
	return cmp.Or(
		cmp.Compare(a.file, b.file),
		cmp.Compare(a.line, b.line),
		cmp.Compare(a.col, b.col),
		cmp.Compare(a.msg, b.msg),
	)
}

func goEnv() []string {
	return append(os.Environ(), "GOWORK=off")
}

func scan(root string) (*module, []genError) {
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedModule,
		Dir:  root,
		Env:  goEnv(),
	}
	pkgs, err := packages.Load(cfg, "./...")
	if err != nil {
		return nil, []genError{{msg: err.Error()}}
	}
	slices.SortFunc(pkgs, func(a, b *packages.Package) int { return cmp.Compare(a.PkgPath, b.PkgPath) })
	mod := &module{}
	fset := token.NewFileSet()
	var errs []genError
	for _, p := range pkgs {
		if mod.path == "" && p.Module != nil && p.Module.Main {
			mod.path = p.Module.Path
		}
		info, perrs := scanPackage(fset, p)
		errs = append(errs, perrs...)
		if info != nil {
			mod.pkgs = append(mod.pkgs, info)
		}
	}
	return mod, errs
}

func scanPackage(fset *token.FileSet, p *packages.Package) (*pkgInfo, []genError) {
	info := &pkgInfo{path: p.PkgPath, name: p.Name, dir: p.Dir}
	if info.dir == "" && len(p.GoFiles) > 0 {
		info.dir = filepath.Dir(p.GoFiles[0])
	}
	if info.dir == "" {
		return nil, nil
	}
	var (
		files  []*ast.File
		listed bool
		errs   []genError
	)
	for _, name := range slices.Sorted(slices.Values(p.GoFiles)) {
		if filepath.Base(name) == genFile {
			listed = true
			continue
		}
		f, err := parser.ParseFile(fset, name, nil, parser.ParseComments|parser.SkipObjectResolution)
		errs = append(errs, parseErrors(name, err)...)
		if f != nil {
			files = append(files, f)
		}
	}
	marked, merrs := findMarked(fset, files)
	errs = append(errs, merrs...)
	info.types = marked
	gen := filepath.Join(info.dir, genFile)
	if !listed && len(marked) > 0 {
		_, err := os.Lstat(gen)
		listed = err == nil
	}
	if listed {
		ours, err := hasHeader(gen)
		switch {
		case err != nil:
			errs = append(errs, genError{file: gen, msg: err.Error()})
		case ours:
			info.genOurs = true
		default:
			info.foreign = true
			errs = append(errs, genError{file: gen, line: 1, col: 1, msg: fmt.Sprintf("%s was not generated by cmd/reset: its first line is not %q", genFile, genHeader)})
		}
	}
	return info, errs
}

func parseErrors(file string, err error) []genError {
	if err == nil {
		return nil
	}
	var list scanner.ErrorList
	if !errors.As(err, &list) {
		return []genError{{file: file, msg: err.Error()}}
	}
	out := make([]genError, len(list))
	for i, e := range list {
		out[i] = genError{file: e.Pos.Filename, line: e.Pos.Line, col: e.Pos.Column, msg: e.Msg}
	}
	return out
}

func findMarked(fset *token.FileSet, files []*ast.File) ([]*markedType, []genError) {
	var (
		marked []*markedType
		byName = map[string]*markedType{}
		errs   []genError
	)
	for _, f := range files {
		errs = append(errs, localMarkers(fset, f)...)
		for _, decl := range f.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok || !hasMarker(specDoc(gd, ts)) {
					continue
				}
				mt, serrs := markedSpec(fset, ts)
				errs = append(errs, serrs...)
				if mt != nil {
					marked = append(marked, mt)
					byName[mt.name] = mt
				}
			}
		}
	}
	for _, f := range files {
		for _, decl := range f.Decls {
			fd, ok := decl.(*ast.FuncDecl)
			if !ok || fd.Recv == nil || len(fd.Recv.List) == 0 {
				continue
			}
			id := baseIdent(fd.Recv.List[0].Type)
			if id == nil {
				continue
			}
			mt := byName[id.Name]
			if mt == nil {
				continue
			}
			if fd.Name.Name == "Reset" {
				errs = append(errs, posError(fset, fd.Name.Pos(), "%s has a hand-written Reset method that conflicts with the generated one", mt.name))
				mt.invalid = true
			}
			if !mt.hasMethod {
				mt.hasMethod = true
				if names := fd.Recv.List[0].Names; len(names) > 0 {
					mt.recv = names[0].Name
				}
			}
		}
	}
	return marked, errs
}

func markedSpec(fset *token.FileSet, ts *ast.TypeSpec) (*markedType, []genError) {
	name := ts.Name.Name
	st, isStruct := ts.Type.(*ast.StructType)
	switch {
	case ts.Assign.IsValid():
		return nil, []genError{posError(fset, ts.Name.Pos(), "cannot generate Reset for type alias %s: generate:reset is allowed only on \"type T struct{...}\" declarations", name)}
	case !isStruct:
		return nil, []genError{posError(fset, ts.Name.Pos(), "cannot generate Reset for %s: generate:reset is allowed only on \"type T struct{...}\" declarations", name)}
	case name == "_":
		return nil, []genError{posError(fset, ts.Name.Pos(), "cannot generate Reset for the blank type name")}
	}
	pos := fset.Position(ts.Name.Pos())
	mt := &markedType{name: name, file: pos.Filename, offset: pos.Offset}
	if ts.TypeParams != nil {
		for _, f := range ts.TypeParams.List {
			mt.tparams += len(f.Names)
		}
	}
	var errs []genError
	for _, field := range st.Fields.List {
		if len(field.Names) == 0 {
			if id := baseIdent(field.Type); id != nil && id.Name == "Reset" {
				errs = append(errs, posError(fset, id.Pos(), "%s has an embedded field named Reset that conflicts with the generated Reset method", name))
			}
			continue
		}
		for _, n := range field.Names {
			if n.Name == "Reset" {
				errs = append(errs, posError(fset, n.Pos(), "%s has a field named Reset that conflicts with the generated Reset method", name))
			}
		}
	}
	mt.invalid = len(errs) > 0
	return mt, errs
}

func specDoc(gd *ast.GenDecl, ts *ast.TypeSpec) *ast.CommentGroup {
	if !gd.Lparen.IsValid() {
		return gd.Doc
	}
	return ts.Doc
}

func localMarkers(fset *token.FileSet, f *ast.File) []genError {
	top := map[ast.Decl]bool{}
	for _, decl := range f.Decls {
		top[decl] = true
	}
	var errs []genError
	ast.Inspect(f, func(n ast.Node) bool {
		gd, ok := n.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE || top[gd] {
			return true
		}
		for _, spec := range gd.Specs {
			if ts, ok := spec.(*ast.TypeSpec); ok && hasMarker(specDoc(gd, ts)) {
				errs = append(errs, posError(fset, ts.Name.Pos(), "cannot generate Reset for local type %s: generate:reset applies only to package-level struct types", ts.Name.Name))
			}
		}
		return true
	})
	return errs
}

func hasMarker(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}
	for _, c := range doc.List {
		if line := strings.TrimSpace(c.Text); line == "// generate:reset" || line == "//generate:reset" {
			return true
		}
	}
	return false
}

func baseIdent(e ast.Expr) *ast.Ident {
	for {
		switch x := e.(type) {
		case *ast.Ident:
			return x
		case *ast.SelectorExpr:
			return x.Sel
		case *ast.StarExpr:
			e = x.X
		case *ast.ParenExpr:
			e = x.X
		case *ast.IndexExpr:
			e = x.X
		case *ast.IndexListExpr:
			e = x.X
		default:
			return nil
		}
	}
}

func hasHeader(path string) (bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return false, err
	}
	defer f.Close()
	line, err := bufio.NewReader(f).ReadString('\n')
	if err != nil && !errors.Is(err, io.EOF) {
		return false, err
	}
	return strings.TrimRight(line, "\r\n") == genHeader, nil
}

func stubs(pkgs []*pkgInfo) map[string][]byte {
	overlay := map[string][]byte{}
	for _, p := range pkgs {
		if p.foreign {
			continue
		}
		var b strings.Builder
		fmt.Fprintf(&b, "package %s\n", p.name)
		n := 0
		for _, t := range p.types {
			if t.invalid {
				continue
			}
			params := ""
			if t.tparams > 0 {
				params = "[" + strings.Repeat("_, ", t.tparams-1) + "_]"
			}
			fmt.Fprintf(&b, "\nfunc (x *%s%s) Reset() {}\n", t.name, params)
			n++
		}
		if n == 0 && !p.genOurs {
			continue
		}
		overlay[filepath.Join(p.dir, genFile)] = []byte(b.String())
	}
	return overlay
}

func verify(root string, overlay map[string][]byte) []genError {
	_, _, errs := typecheck(root, overlay)
	for i := range errs {
		errs[i].msg = "generated code does not compile: " + errs[i].msg
	}
	return errs
}

func typecheck(root string, overlay map[string][]byte) (*token.FileSet, map[string]*types.Package, []genError) {
	fset := token.NewFileSet()
	cfg := &packages.Config{
		Mode:    packages.NeedName | packages.NeedFiles | packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo,
		Dir:     root,
		Env:     goEnv(),
		Fset:    fset,
		Overlay: overlay,
	}
	pkgs, err := packages.Load(cfg, "./...")
	if err != nil {
		return nil, nil, []genError{{msg: err.Error()}}
	}
	typed := map[string]*types.Package{}
	var errs []genError
	for _, p := range pkgs {
		checked := slices.ContainsFunc(p.Errors, func(e packages.Error) bool {
			return e.Kind == packages.TypeError || e.Kind == packages.ParseError
		})
		for _, e := range p.Errors {
			if checked && e.Kind == packages.ListError && strings.HasPrefix(e.Msg, "# ") {
				continue
			}
			errs = append(errs, loadError(root, e))
		}
		if p.Types != nil {
			typed[p.PkgPath] = p.Types
		}
	}
	return fset, typed, errs
}

func loadError(root string, e packages.Error) genError {
	file, line, col := splitPos(e.Pos)
	if file != "" && !filepath.IsAbs(file) {
		file = filepath.Join(root, file)
	}
	return genError{file: file, line: line, col: col, msg: e.Msg}
}

func splitPos(pos string) (string, int, int) {
	file, line, col := pos, 0, 0
	if i := strings.LastIndexByte(file, ':'); i >= 0 {
		if n, err := strconv.Atoi(file[i+1:]); err == nil {
			file, line = file[:i], n
			if j := strings.LastIndexByte(file, ':'); j >= 0 {
				if m, err := strconv.Atoi(file[j+1:]); err == nil {
					file, line, col = file[:j], m, n
				}
			}
		}
	}
	if file == "-" {
		file = ""
	}
	return file, line, col
}
