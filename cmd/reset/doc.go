// Reset генерирует методы Reset() для структур модуля, размеченных
// комментарием generate:reset. Метод возвращает объект к начальному
// состоянию и по возможности сохраняет выделенную память, поэтому объект
// можно использовать повторно, например через sync.Pool.
//
// Команда находит корень модуля — ближайший каталог с go.mod вверх от
// текущего — и обрабатывает все пакеты модуля по правилам шаблона ./...:
// каталоги testdata, vendor, каталоги с именами на «.» и «_», а также
// вложенные модули пропускаются. Файлы *_test.go не сканируются. Пакеты
// загружаются через golang.org/x/tools/go/packages, и вид каждого поля
// определяется по информации о типах go/types, а не по написанию, поэтому
// именованные типы, алиасы и типы других пакетов обрабатываются одинаково.
//
// # Маркер
//
// Структура размечена, если в её doc-комментарии есть строка, которая после
// удаления пробелов по краям равна «// generate:reset» или
// «//generate:reset». Кроме маркера, в комментарии могут быть и другие
// строки. В группе type ( … ) учитывается только комментарий непосредственно
// над конкретным типом, а комментарий, отделённый от типа пустой строкой, к
// типу не относится. Маркер допустим только над объявлением уровня пакета
// вида type T struct{…}, в том числе обобщённым:
//
//	// generate:reset
//	type ResetableStruct struct {
//		i     int
//		str   string
//		strP  *string
//		s     []int
//		m     map[string]string
//		child *ResetableStruct
//	}
//
// Маркер над типом, объявленным внутри функции, — ошибка: метод для
// локального типа объявить нельзя.
//
// # Правила сброса
//
// Метод получает получатель-указатель, начинается с проверки получателя на
// nil и сбрасывает поля в порядке объявления. Поля _ пропускаются, а
// встроенные поля сбрасываются так же, как обычные.
//
//   - Числа получают 0, строки — "", bool — false, unsafe.Pointer — nil.
//   - Слайс усекается до длины 0 с сохранением ёмкости. Если тип элемента
//     содержит указатели, элементы сначала обнуляются встроенной функцией
//     clear, чтобы слайс не удерживал объекты прошлого использования.
//     Слайс элементов-параметров типа очищается всегда: тип элемента может
//     содержать указатели.
//   - Мапа очищается функцией clear и остаётся тем же объектом.
//   - Если в наборе методов указателя на именованный тип есть метод Reset
//     без параметров и результатов, в том числе полученный через встраивание,
//     вызывается он. Размеченные структуры этого и других пакетов модуля
//     считаются такими типами, даже если их reset.gen.go ещё не создан. Если
//     Reset() получен через встроенный указатель или интерфейс, перед
//     вызовом каждый такой шаг пути встраивания проверяется на nil: если
//     хотя бы один шаг равен nil, вызова нет и поле не меняется.
//   - Интерфейсы, каналы и функции получают nil, даже если в наборе методов
//     интерфейса есть Reset().
//   - Структура без Reset() получает нулевое значение своего типа. Анонимная
//     структура обнуляется всегда, и по значению, и под указателем, даже если
//     через встраивание у неё есть Reset().
//   - У не-nil указателя сбрасывается значение под ним по тем же правилам, а
//     у указателя на именованный тип с Reset() вызывается Reset(). Каждый
//     уровень многоуровневого указателя проверяется на nil.
//   - Массив сбрасывается поэлементно, если для типа элемента действует особое
//     правило (слайс, мапа, указатель, тип с Reset() или массив таких
//     элементов), иначе получает нулевое значение целиком.
//   - Поле параметра типа сбрасывается вызовом Reset(), если его требует
//     ограничение, иначе получает нулевое значение *new(T).
//
// # Файл reset.gen.go
//
// Методы всех размеченных структур пакета записываются в один файл
// reset.gen.go этого пакета в порядке объявления структур. Первая строка
// файла — «// Code generated by cmd/reset; DO NOT EDIT.», других комментариев
// в нём нет. Импорты сгруппированы так же, как у goimports -local с путём
// модуля. Файл перезаписывается, только если его содержимое изменилось,
// поэтому повторный запуск ничего не меняет. Если в пакете не осталось
// размеченных структур, файл с этой шапкой удаляется.
//
// # Ошибки и конфликты
//
// Генерация идёт по принципу «всё или ничего»: если найдена хотя бы одна
// ошибка в любом пакете, ни один файл не создаётся, не изменяется и не
// удаляется. Ошибками считаются:
//
//   - маркер над типом, который не является структурой уровня пакета;
//   - написанный вручную метод Reset или поле Reset у размеченной структуры;
//   - reset.gen.go без шапки генератора;
//   - объявление уровня пакета, которое затеняет предобъявленный
//     идентификатор, нужный сгенерированному коду этого пакета (clear, new,
//     nil, false, имена базовых типов и т. п.);
//   - параметр типа размеченной структуры с именем предобъявленного
//     идентификатора (max, new, int и т. п.);
//   - ошибки разбора и проверки типов в нетестовых файлах модуля;
//   - сгенерированный код, который не проходит проверку типов вместе со
//     своим пакетом, например потому, что тип поля нельзя назвать из пакета
//     структуры.
//
// Если ошибки найдены уже при разборе исходников и поиске маркеров, проверка
// типов не выполняется, чтобы не печатать следствия этих ошибок. Типы
// проверяются так, будто сгенерированные методы уже на месте: код, который
// вызывает Reset() размеченной структуры, загружается и до первого запуска,
// а вызов Reset() у типа со снятым маркером становится ошибкой. Перед
// записью модуль проверяется ещё раз, уже с настоящим содержимым новых
// reset.gen.go, а удаляемые файлы при этом не учитываются. Ошибки этой
// проверки указывают позицию в будущем reset.gen.go.
//
// # Использование
//
// Запуск без аргументов из корня модуля:
//
//	go run ./cmd/reset
//
// Из любого подкаталога модуля команда запускается по полному пути пакета
// или собранным бинарём и всё равно обрабатывает модуль целиком:
//
//	go run practice/cmd/reset
//
// При успехе команда ничего не печатает. Каждая ошибка печатается в stderr
// ровно одной строкой. Если ошибка относится к месту в исходнике, строка
// начинается с позиции: файл:строка:столбец: сообщение. Многострочное
// сообщение склеивается в одну строку через «; ».
//
// # Коды завершения
//
//   - 0: файлы сгенерированы или уже актуальны.
//   - 1: модуль не найден, найдены ошибки или не удалось записать файл.
//
// # Ограничения
//
// Видны только файлы текущих GOOS и GOARCH: маркер в файле, исключённом
// build-ограничениями, не обрабатывается. Защиты от циклов нет: на
// циклической структуре ссылок через указатели Reset() уходит в бесконечную
// рекурсию. Reset(), полученный через встраивание, сбрасывает только
// встроенную часть. Сброс через указатель меняет значение под ним для всех,
// кто на него ссылается. Значение параметра типа на nil не проверяется: если
// ограничение требует Reset(), параметр инстанцирован указателем (R = *T), а
// поле равно nil, вызов Reset() может паниковать.
