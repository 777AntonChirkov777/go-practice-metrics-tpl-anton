// Linter проверяет пакеты проекта статическим анализатором panicexit,
// построенным на golang.org/x/tools/go/analysis/singlechecker.
//
// Анализатор сообщает о каждом использовании встроенной функции panic, где бы
// оно ни стояло, в том числе в функции main. Об обращениях к os.Exit,
// log.Fatal, log.Fatalf, log.Fatalln и к методам Fatal, Fatalf и Fatalln типа
// *log.Logger он сообщает, если они стоят вне тела функции main пакета main.
// Телом main считается весь её текст, включая вложенные функциональные
// литералы, defer и go. Функция init, методы с именем main, инициализаторы
// переменных уровня пакета и функция main в пакете с другим именем считаются
// местами вне main.
//
// Функции распознаются по информации о типах. Учитываются вызовы, значения
// функций, method value и method expression, псевдонимы импорта, dot-import и
// методы, полученные через встраивание. Собственные функции с теми же именами
// и перекрытая локальным объявлением panic не сообщаются. Файлы *_test.go и
// сгенерированные файлы, помеченные строкой «Code generated … DO NOT EDIT.»,
// не проверяются. Файлы с import "C" (cgo) тоже не проверяются: анализатор
// получает только их вывод cmd/cgo, а он помечен как сгенерированный.
//
// # Использование
//
//	linter [флаги] [пакеты]
//
// Проверка всего проекта из корня репозитория:
//
//	go run ./cmd/linter ./...
//
// Собранный бинарь можно подключить к go vet:
//
//	go build -o panicexit ./cmd/linter
//	go vet -vettool=/полный/путь/к/panicexit ./...
//
// Каждая находка печатается в виде файл:строка:столбец: сообщение, например
// «use of builtin panic» или «use of os.Exit outside function main of package
// main». Флаги драйвера singlechecker, например -json и -c, перечисляет -help.
//
// # Коды завершения
//
//   - 0: нарушений нет.
//   - 1: пакеты не заданы, их не удалось загрузить или проанализировать.
//   - 3: найдено хотя бы одно нарушение.
//
// С флагом -json находки печатаются в формате JSON, и код завершения в этом
// режиме равен 0 даже при найденных нарушениях.
