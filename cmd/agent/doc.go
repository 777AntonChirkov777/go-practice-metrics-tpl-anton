// Agent собирает метрики работающего процесса и системы и периодически
// отправляет их на сервер метрик.
//
// Агент работает до сигнала SIGINT или SIGTERM, после чего дожидается
// завершения своих горутин. Реализация находится в пакете
// practice/internal/agent.
//
// # Использование
//
//	agent [флаги]
//
// # Флаги и переменные окружения
//
// Настройки собираются из трёх источников: значения по умолчанию, флаги,
// переменные окружения. Переменная окружения важнее флага, флаг важнее
// значения по умолчанию. Числа в переменных окружения должны быть больше нуля:
// иначе значение не применяется. Если флаги не удалось разобрать (неизвестный
// флаг, нечисловое значение, интервал или предел не больше нуля), они не
// применяются целиком, причина пишется в лог, и действуют значения по
// умолчанию. Если переменные окружения не удалось разобрать, они не
// применяются целиком. Запуск при этом не прерывается.
//
//   - -a, ADDRESS: адрес сервера в виде host:port, по умолчанию
//     localhost:8080. К адресу добавляется схема http://.
//   - -r, REPORT_INTERVAL: период отправки метрик на сервер в секундах, по
//     умолчанию 10.
//   - -p, POLL_INTERVAL: период опроса метрик в секундах, по умолчанию 2.
//   - -k, KEY: ключ подписи HashSHA256, по умолчанию пустой, подпись отключена.
//   - -l, RATE_LIMIT: предел одновременно исходящих запросов к серверу, по
//     умолчанию 1.
//
// Значения 10 и 2 секунды, которые действуют при пустой командной строке,
// взяты из флагов. Значения 30 и 5 секунд из структуры настроек действуют,
// только если разбор флагов завершился ошибкой, а соответствующая переменная
// окружения не применена.
//
// # Что собирается
//
// Каждые -p секунд агент обновляет метрики пакета runtime (27 gauge из полей
// runtime.MemStats, например Alloc, HeapAlloc и NumGC), gauge RandomValue со
// случайным значением, counter PollCount, который растёт на единицу при каждом
// опросе, а также системные gauge TotalMemory, FreeMemory и CPUutilization1,
// CPUutilization2 и так далее по числу процессоров.
//
// # Отправка
//
// Каждые -r секунд агент формирует пакет с текущими значениями всех собранных
// метрик и отправляет его запросом POST /updates/ на адрес сервера. Тело запроса это
// JSON-массив метрик, сжатый gzip, с заголовками Content-Type:
// application/json и Content-Encoding: gzip. Если задан ключ, то в заголовке
// HashSHA256 передаётся подпись несжатого JSON-тела. Одновременно выполняется
// не более -l запросов; если все заняты, отправка ждёт освобождения. Таймаут
// одного запроса 5 секунд. При временных ошибках (сетевые сбои, ответы 408, 429
// и 5xx) отправка повторяется с паузами 1, 3 и 5 секунд; превышение таймаута
// запроса повтор не вызывает.
