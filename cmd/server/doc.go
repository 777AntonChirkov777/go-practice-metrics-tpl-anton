// Server запускает HTTP-сервер сбора метрик типов gauge и counter.
//
// Сервер принимает метрики от агента и клиентов по HTTP, отдаёт их значения
// и хранит их в базе данных либо в памяти, при необходимости сохраняя в файл.
// Маршруты описаны в пакете practice/internal/server, обработчики — в пакете
// practice/internal/handler. Работа завершается по сигналу SIGINT или SIGTERM:
// сервер штатно останавливается, ожидая завершения запросов не дольше
// 5 секунд, затем метрики сохраняются в файл (если используется файловое
// хранение) и закрываются приёмники аудита.
//
// # Использование
//
//	server [флаги]
//
// # Флаги и переменные окружения
//
// Настройки собираются из трёх источников: значения по умолчанию, флаги,
// переменные окружения. Переменная окружения важнее флага, флаг важнее
// значения по умолчанию. Незаданные и пустые переменные окружения
// игнорируются. Если флаг неизвестен, его значение или переменную окружения
// не удалось разобрать (например, нечисловое STORE_INTERVAL), либо остались
// позиционные аргументы, сервер завершается с кодом 1 и сообщением об ошибке
// конфигурации.
//
//   - -a, ADDRESS: адрес сервера, по умолчанию localhost:8080. Из адреса
//     используется только порт, сервер слушает его на всех интерфейсах.
//   - -i, STORE_INTERVAL: период сброса метрик на диск в секундах, по умолчанию
//     300. Значение 0 (или меньше) включает синхронную запись при каждом
//     обновлении.
//   - -f, FILE_STORAGE_PATH: путь к файлу с метриками, по умолчанию
//     metrics-db.json. Пустой путь отключает работу с файлом.
//   - -r, RESTORE: загружать ли сохранённые метрики из файла при старте, по
//     умолчанию true.
//   - -d, DATABASE_DSN: строка подключения к PostgreSQL, по умолчанию пустая.
//   - -k, KEY: ключ подписи HashSHA256, по умолчанию пустой.
//   - -audit-file, AUDIT_FILE: путь к файлу журнала аудита, по умолчанию пустой.
//   - -audit-url, AUDIT_URL: URL приёмника аудита по HTTP, по умолчанию пустой.
//
// # Выбор хранилища
//
// Если задан DSN, метрики хранятся в базе данных: при старте проверяется
// связь с базой и применяются миграции, ошибки этих шагов только пишутся в
// лог. Если DSN пустой, метрики хранятся в памяти. Корректность DSN
// проверяется по формату, и при некорректном DSN ошибка пишется в лог, а
// сервер переходит к хранению в памяти. При хранении в памяти и непустом пути
// к файлу метрики при старте загружаются из файла (если восстановление
// включено через -r или RESTORE) и сохраняются в него: каждые -i секунд, а при
// интервале 0 или меньше синхронно при каждом обновлении; итоговое сохранение
// выполняется и при остановке. При пустом пути метрики живут только в памяти.
//
// # Подпись
//
// Если задан ключ, сервер проверяет заголовок HashSHA256 у запросов, где он
// передан, и подписывает ответы. Запрос с неверной подписью получает ответ 400
// с текстом invalid hash.
//
// # Аудит
//
// Приёмники аудита включаются независимо: файловый при заданном пути и
// удалённый при заданном URL. Если оба не заданы, аудит отключён. Событие
// содержит время, имена обновлённых метрик и IP-адрес клиента. Некорректный
// URL приёмника или файл, который не удалось открыть, прерывают запуск с
// ошибкой.
